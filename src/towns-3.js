/*
 * Arab-country cities added from Egyptian Search Console data (October 2026): Arabic searches for one
 * adhan at a time, across Egypt and the other Arab countries. Same format as towns.js and towns-2.js:
 *
 * T(english, lat, lng, 'ur|hi|bn|fa', { ar, other languages, alt }, timeZone)
 * R(english, 'ur|hi|bn|fa', { ar, ... }, [towns])   ('' names = region already exists)
 *
 * Gulf countries and Iraq have Urdu, Hindi, Bengali or Persian pages, so their towns carry those names too.
 */
'use strict';

function split(s) {
  if (!s) return {};
  var p = s.split('|');
  return { ur: p[0], hi: p[1], bn: p[2], fa: p[3] };
}
// Urdu, Hindi, Bengali and Persian names for places given '' below (every place needs them).
var N4 = require('./towns-3-names');
function T(en, lat, lng, names, extra, tz) { return [en, lat, lng, Object.assign(split(names || N4[en]), extra || {}), tz]; }
function R(en, names, extra, cities) { return { name: Object.assign({ en: en }, split(names || (extra && extra.ar ? N4[en] : '')), extra || {}), cities: cities }; }

