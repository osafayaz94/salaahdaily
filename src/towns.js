/*
 * Additional major towns, merged into data.js by the build.
 * A region whose English name already exists in that country gets the towns appended;
 * otherwise a new region is created.
 *
 * T(english, lat, lng, 'ur|hi|bn|fa', { other languages }, timeZone)
 * R(english, 'ur|hi|bn|fa', { other languages }, [towns])   ('' names = region already exists)
 */
function split(s) {
  if (!s) return {};
  var p = s.split('|');
  return { ur: p[0], hi: p[1], bn: p[2], fa: p[3] };
}
function T(en, lat, lng, names, extra, tz) { return [en, lat, lng, Object.assign(split(names), extra || {}), tz]; }
function R(en, names, extra, cities) { return { name: Object.assign({ en: en }, split(names), extra || {}), cities: cities }; }

